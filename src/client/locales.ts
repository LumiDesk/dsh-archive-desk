export const dictionaries = { zh, en }

/** Keys translated by the panel; used by the parity test. */
export function dictionaryKeys(): { zh: string[]; en: string[] } {
  return { zh: Object.keys(zh).sort(), en: Object.keys(en).sort() }
}

/** Replace `{name}` placeholders without interpreting the replacement text. */
export function formatMessage(
  template: string,
  params: Record<string, string | number> = {},
): string {
  return template.replace(/\{([a-zA-Z0-9_.-]+)\}/g, (match, key: string) => {
    const value = params[key]
    return value === undefined ? match : String(value)
  })
}
